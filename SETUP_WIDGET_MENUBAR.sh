    exit 1
fi

echo "✅ Found FocusOS.xcodeproj"
echo ""
echo "Manual steps required in Xcode:"
echo "================================="
echo ""
echo "1️⃣  CREATE SHARED FRAMEWORK TARGET"
echo "   - File > New > Target"
echo "   - macOS > Framework"
echo "   - Name: FocusOSShared"
echo "   - Bundle ID: com.kosmicapps.FocusOS.FocusOSShared"
echo "   - Team: Your team"
echo "   - Click Finish"
echo ""
echo "2️⃣  CREATE WIDGET EXTENSION TARGET"
echo "   - File > New > Target"
echo "   - macOS > Widget Extension"
echo "   - Name: FocusOSWidget"
echo "   - Bundle ID: com.kosmicapps.FocusOS.FocusOSWidget"
echo "   - Include Configuration Intent: NO"
echo "   - Team: Your team"
echo "   - Click Finish"
echo ""
echo "3️⃣  CREATE MENU BAR APP TARGET"
echo "   - File > New > Target"
echo "   - macOS > App"
echo "   - Name: FocusOSMenuBar"
echo "   - Bundle ID: com.kosmicapps.FocusOS.FocusOSMenuBar"
echo "   - Language: Swift"
echo "   - Team: Your team"
echo "   - Click Finish"
echo ""
echo "4️⃣  ADD APP GROUP ENTITLEMENT TO MAIN APP"
echo "   - Select FocusOS target"
echo "   - Go to Signing & Capabilities tab"
echo "   - Click + Capability"
echo "   - Add 'App Groups'"
echo "   - Add group: group.kosmicapps.focusos"
echo "   - Enable 'iCloud' capability with CloudKit"
echo ""
echo "5️⃣  ADD APP GROUP TO SHARED FRAMEWORK"
echo "   - Select FocusOSShared target"
echo "   - Go to Signing & Capabilities tab"
echo "   - Click + Capability"
echo "   - Add 'App Groups'"
echo "   - Add group: group.kosmicapps.focusos"
echo ""
echo "6️⃣  ADD APP GROUP TO WIDGET"
echo "   - Select FocusOSWidget target"
