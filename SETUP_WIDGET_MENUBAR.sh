echo "   - Add group: group.kosmicapps.focusos"
echo "   - Add 'App Sandbox' capability"
echo "   - Enable 'Outgoing Connections'"
echo ""
echo "8️⃣  ADD FILES TO TARGETS"
echo "   For FocusOSShared:"
echo "   - Add FocusOSShared/FocusOSShared/Models/*.swift"
echo "   - Add FocusOSShared/FocusOSShared/Services/*.swift"
echo "   - Add FocusOSShared/FocusOSShared/UI/*.swift"
echo "   - Add FocusOSShared/FocusOSShared/SharedDataManager.swift"
echo ""
echo "   For FocusOSWidget:"
echo "   - Add FocusOSWidget/*.swift"
echo ""
echo "   For FocusOSMenuBar:"
echo "   - Add FocusOSMenuBar/*.swift"
echo ""
